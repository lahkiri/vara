export const dicts = { ar, en };

export const i18n = $state<{ lang: Lang }>({ lang: "ar" });

export function t(key: keyof typeof ar): string {
  return dicts[i18n.lang][key] ?? key;
}

export function setLang(l: Lang) {
  i18n.lang = l;
  try {
    localStorage.setItem("vara_lang", l);
  } catch { /* ignore */ }
  applyLangDom(l);
}

export function applyLangDom(l: Lang) {
  document.documentElement.lang = l;
  document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
}

export function loadLang(): Lang {
  try {
    const l = localStorage.getItem("vara_lang");
    if (l === "ar" || l === "en") {
      i18n.lang = l;
      applyLangDom(l);
      return l;
    }
  } catch { /* ignore */ }
  applyLangDom("ar");
  return "ar";
}
